// Run from any directory: node new-year-portal/build.cjs
const fs=require('node:fs');
const path=require('node:path');
const os=require('node:os');
const {execFileSync}=require('node:child_process');
const root=__dirname;
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const patch=fs.readFileSync(path.join(root,'patch-banquets/banquets-static.css'),'utf8');
const marker='/* BEGIN STATIC BANQUETS — generated by build.cjs */';
let css=fs.readFileSync(path.join(root,'styles.css'),'utf8').split(marker)[0].trimEnd();
fs.writeFileSync(path.join(root,'styles.css'),css+'\n\n'+marker+'\n'+patch);
const main=html.match(/<main class="new-year-page">[\s\S]*?<\/main>/)[0];
fs.writeFileSync(path.join(root,'page-content.html'),main+'\n');
const section=html.match(/<section class="section wrap" aria-label="Новогодние банкеты">[\s\S]*?<\/section>/)[0];
fs.writeFileSync(path.join(root,'patch-banquets/banquets-section.html'),section+'\n');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'portal-source-'));
fs.cpSync(root,path.join(temp,'new-year-portal'),{recursive:true,filter:p=>!p.endsWith('.DS_Store')});
execFileSync('zip',['-qr',path.join(temp,'source.zip'),'new-year-portal'],{cwd:temp});
fs.copyFileSync(path.join(temp,'source.zip'),path.join(root,'../downloads/new-year-portal-full-source.zip'));
fs.rmSync(temp,{recursive:true,force:true});
console.log('Built full page fragment, banquet-only HTML and full source archive');
